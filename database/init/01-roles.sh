#!/bin/bash
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
CREATE ROLE role_admin LOGIN PASSWORD '$ROLE_ADMIN_PASSWORD';
CREATE ROLE role_nhan_vien LOGIN PASSWORD '$ROLE_STAFF_PASSWORD';
CREATE ROLE role_khach_hang LOGIN PASSWORD '$ROLE_CUSTOMER_PASSWORD';

GRANT CONNECT ON DATABASE "$POSTGRES_DB" TO role_admin, role_nhan_vien, role_khach_hang;
GRANT USAGE ON SCHEMA public TO role_admin, role_nhan_vien, role_khach_hang;

ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO role_admin;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE ON TABLES TO role_nhan_vien;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO role_khach_hang;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO role_admin, role_nhan_vien;
EOSQL